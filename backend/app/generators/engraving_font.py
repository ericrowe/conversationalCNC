def get_glyph(char: str, font_name: str = "simplex_sans", curve_subdivisions: int = 4) -> Dict[str, Any]:
    """
    Returns glyph stroke definitions for the given character and font,
    applying spline curve interpolation smoothing with curve_subdivisions.
    """
    font_dict = FONTS.get(font_name, SIMPLEX_SANS)
    raw = font_dict.get(char, SIMPLEX_SANS.get(char, SIMPLEX_SANS.get("?", {"w": 4.0, "strokes": []})))

    # Apply curve smoothing to each stroke
    if curve_subdivisions > 1:
        smoothed_strokes = [smooth_stroke(stroke, steps=curve_subdivisions) for stroke in raw["strokes"]]
        return {"w": raw["w"], "strokes": smoothed_strokes}
    return raw
