# 4. Cursive Script (Slanted, flowing cursive with natural loop flourishes)
def _make_cursive_script_glyphs() -> Dict[str, Dict[str, Any]]:
    d: Dict[str, Dict[str, Any]] = {}
    slant = 0.25  # 15-degree slant shift (x = x + y * slant)

    for char, g in SIMPLEX_SANS.items():
        w = g["w"] + 1.0
        strokes = []
        for poly in g["strokes"]:
            slanted = [(round(px + py * slant, 3), py) for (px, py) in poly]
            strokes.append(slanted)
        d[char] = {"w": round(w, 2), "strokes": strokes}

    # Distinctive script flourishes for key letters
    d["A"] = {"w": 7.5, "strokes": [[(1.0, 2.0), (2.5, 9.0), (4.5, 10.0), (6.5, 1.0), (8.0, 0.0)], [(2.5, 4.5), (6.0, 4.5)]]}
    d["B"] = {"w": 7.0, "strokes": [[(1.5, 0.0), (3.0, 10.0)], [(3.0, 10.0), (5.5, 9.5), (6.5, 7.5), (5.0, 5.5), (2.5, 5.5)], [(5.0, 5.5), (7.0, 4.0), (6.5, 1.0), (4.5, 0.0), (2.0, 0.0)]]}
    d["C"] = {"w": 7.0, "strokes": [[(6.5, 8.5), (4.5, 10.0), (2.0, 8.0), (1.5, 3.5), (3.0, 0.5), (5.5, 0.0), (7.0, 1.5)]]}
    d["e"] = {"w": 5.5, "strokes": [[(0.5, 0.5), (2.0, 4.0), (4.5, 4.0), (4.5, 6.0), (3.0, 7.0), (1.5, 5.0), (1.5, 2.0), (3.0, 0.0), (5.5, 0.0)]]}
    d["l"] = {"w": 4.0, "strokes": [[(0.5, 0.0), (2.5, 8.0), (3.5, 10.0), (2.5, 10.0), (1.5, 4.0), (2.5, 0.0), (4.0, 0.0)]]}
    return d

CURSIVE_SCRIPT = _make_cursive_script_glyphs()


