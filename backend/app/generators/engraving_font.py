# 2. Duplex Bold Sans (Double-stroke / Parallel lines for bold presence)
def _make_duplex_glyphs() -> Dict[str, Dict[str, Any]]:
    d: Dict[str, Dict[str, Any]] = {}
    for char, g in SIMPLEX_SANS.items():
        w = g["w"] + 0.8
        strokes = []
        for poly in g["strokes"]:
            if len(poly) >= 2:
                # Main line
                strokes.append(poly)
                # Offset parallel stroke by dx=0.55
                offset_poly = [(round(px + 0.55, 3), py) for (px, py) in poly]
                strokes.append(offset_poly)
            else:
                strokes.append(poly)
        d[char] = {"w": round(w, 2), "strokes": strokes}
    return d

DUPLEX_SANS = _make_duplex_glyphs()


