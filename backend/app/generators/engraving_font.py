def get_glyph(char: str, font_name: str = "simplex_sans") -> Dict[str, Any]:
    """Returns glyph stroke definitions for the given character and font."""
    font_dict = FONTS.get(font_name, SIMPLEX_SANS)
    if char in font_dict:
        return font_dict[char]
    if char in SIMPLEX_SANS:
        return SIMPLEX_SANS[char]
    return SIMPLEX_SANS.get("?", {"w": 4.0, "strokes": []})
