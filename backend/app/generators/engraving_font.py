def smooth_stroke(poly: List[Tuple[float, float]], steps: int = 4, corner_threshold_deg: float = 65.0) -> List[Tuple[float, float]]:
    """
    Subdivides and smooths a polyline using cubic Catmull-Rom spline interpolation
    while preserving sharp corners / cusps above corner_threshold_deg.
    """
    if len(poly) < 3 or steps <= 1:
        return poly

    is_closed = (poly[0] == poly[-1])
    n = len(poly)
    result: List[Tuple[float, float]] = []

    def angle_between(v1: Tuple[float, float], v2: Tuple[float, float]) -> float:
        dot = v1[0] * v2[0] + v1[1] * v2[1]
        m1 = math.hypot(v1[0], v1[1])
        m2 = math.hypot(v2[0], v2[1])
        if m1 == 0 or m2 == 0:
            return 0.0
        cos_val = max(-1.0, min(1.0, dot / (m1 * m2)))
        return math.degrees(math.acos(cos_val))

    for i in range(len(poly) - 1):
        p1 = poly[i]
        p2 = poly[i + 1]

        is_sharp1 = False
        is_sharp2 = False

        if not is_closed:
            if i == 0:
                is_sharp1 = True
            if i + 1 == len(poly) - 1:
                is_sharp2 = True

        if i > 0 and not is_sharp1:
            p_prev = poly[i - 1]
            v_in = (p1[0] - p_prev[0], p1[1] - p_prev[1])
            v_out = (p2[0] - p1[0], p2[1] - p1[1])
            if angle_between(v_in, v_out) > corner_threshold_deg:
                is_sharp1 = True

        if i + 2 < len(poly) and not is_sharp2:
            p_next = poly[i + 2]
            v_in = (p2[0] - p1[0], p2[1] - p1[1])
            v_out = (p_next[0] - p2[0], p_next[1] - p2[1])
            if angle_between(v_in, v_out) > corner_threshold_deg:
                is_sharp2 = True

        if is_closed:
            p0 = poly[(i - 1 + n - 1) % (n - 1)] if not is_sharp1 else p1
            p3 = poly[(i + 2) % (n - 1)] if not is_sharp2 else p2
        else:
            p0 = poly[i - 1] if (i > 0 and not is_sharp1) else (2 * p1[0] - p2[0], 2 * p1[1] - p2[1])
            p3 = poly[i + 2] if (i + 2 < n and not is_sharp2) else (2 * p2[0] - p1[0], 2 * p2[1] - p1[1])

        seg_steps = steps
        num_points = seg_steps if i < len(poly) - 2 else seg_steps + 1
        for s in range(num_points):
            t = s / float(seg_steps)
            t2 = t * t
            t3 = t2 * t

            x = 0.5 * ((2 * p1[0]) + (-p0[0] + p2[0]) * t + (2 * p0[0] - 5 * p1[0] + 4 * p2[0] - p3[0]) * t2 + (-p0[0] + 3 * p1[0] - 3 * p2[0] + p3[0]) * t3)
            y = 0.5 * ((2 * p1[1]) + (-p0[1] + p2[1]) * t + (2 * p0[1] - 5 * p1[1] + 4 * p2[1] - p3[1]) * t2 + (-p0[1] + 3 * p1[1] - 3 * p2[1] + p3[1]) * t3)
            result.append((round(x, 4), round(y, 4)))

    return result


